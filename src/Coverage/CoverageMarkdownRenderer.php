<?php

declare(strict_types=1);

namespace CertPath\Coverage;

/**
 * Renders `docs/syllabus/coverage-report.md`.
 *
 * §19 forbids inventing percentages. When the syllabus has not been imported
 * the report says the denominator is undefined rather than printing "0%",
 * because those are different claims.
 */
final class CoverageMarkdownRenderer
{
    public function render(CoverageReport $report, ?string $syllabusRevision = null): string
    {
        $lines = [];
        $lines[] = '# Coverage report';
        $lines[] = '';
        $lines[] = '> Generated by `bin/cert coverage`. Do not edit by hand.';
        $lines[] = '>';
        $lines[] = '> No generation timestamp is embedded: CI regenerates this file and';
        $lines[] = '> fails on any diff, which a changing timestamp would make impossible.';
        $lines[] = '';
        $lines[] = \sprintf('**Syllabus revision:** %s', $syllabusRevision ?? 'not imported');
        $lines[] = '';
        $lines[] = '## Official coverage (Master Plan §3.5)';
        $lines[] = '';
        $lines[] = '```text';
        $lines[] = 'EXAM_READY atomic official items / total atomic official items * 100';
        $lines[] = '```';
        $lines[] = '';

        if (!$report->isDenominatorEstablished()) {
            $lines[] = '**Coverage: UNDEFINED.**';
            $lines[] = '';

            if ($report->isPartialImport()) {
                $lines[] = \sprintf(
                    'The syllabus import is **incomplete**: %d atomic official items are present,',
                    $report->totalOfficialItems,
                );
                $lines[] = 'but the matrix declares `syllabus_complete: false`, so the total is not';
                $lines[] = 'the real total.';
                $lines[] = '';
                $lines[] = \sprintf(
                    'For the record, %d of the %d imported items are EXAM_READY — but that ratio',
                    $report->examReadyItems,
                    $report->totalOfficialItems,
                );
                $lines[] = 'is **not** the coverage figure and must never be quoted as one. A';
                $lines[] = 'percentage over a partial denominator always reads higher than the';
                $lines[] = 'truth, and reads entirely credible while doing so.';
            } else {
                $lines[] = 'The atomic official syllabus has not been imported, so the denominator';
                $lines[] = 'does not exist. This is deliberately not reported as `0%`: an undefined';
                $lines[] = 'denominator and a zero numerator are different claims (§19).';
            }

            $lines[] = '';

            return implode("\n", $lines)."\n"
                .($report->isPartialImport() ? $this->breakdown($report) : '');
        }

        $lines[] = \sprintf(
            '**Coverage: %s%%** — %d of %d atomic official items are EXAM_READY.',
            $report->percentage(),
            $report->examReadyItems,
            $report->totalOfficialItems,
        );
        $lines[] = '';
        $lines[] = rtrim($this->breakdown($report));
        $lines[] = '';

        return implode("\n", $lines)."\n";
    }

    private function breakdown(CoverageReport $report): string
    {
        $lines = [];
        $lines[] = '## By official topic';
        $lines[] = '';
        $lines[] = '| Official topic | EXAM_READY | Total | % |';
        $lines[] = '|---|---:|---:|---:|';
        foreach ($report->byTopic as $topic => $counts) {
            $lines[] = \sprintf(
                '| %s | %d | %d | %s |',
                $topic,
                $counts['ready'],
                $counts['total'],
                $this->pct($counts['ready'], $counts['total']),
            );
        }
        $lines[] = '';
        $lines[] = '## By lot';
        $lines[] = '';
        $lines[] = '| Lot | EXAM_READY | Total | % |';
        $lines[] = '|---|---:|---:|---:|';
        foreach ($report->byLot as $lot => $counts) {
            $lines[] = \sprintf(
                '| %s | %d | %d | %s |',
                $lot,
                $counts['ready'],
                $counts['total'],
                $this->pct($counts['ready'], $counts['total']),
            );
        }
        $lines[] = '';
        $lines[] = \sprintf('## Not yet EXAM_READY (%d)', \count($report->blockedItemIds));
        $lines[] = '';
        if ([] === $report->blockedItemIds) {
            $lines[] = 'None.';
        } else {
            foreach ($report->blockedItemIds as $id) {
                $lines[] = '- `'.$id.'`';
            }
        }
        $lines[] = '';

        return implode("\n", $lines)."\n";
    }

    private function pct(int $ready, int $total): string
    {
        return 0 === $total ? 'n/a' : \sprintf('%.1f', $ready / $total * 100);
    }
}
